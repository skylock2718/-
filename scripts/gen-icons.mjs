// Extracts only the game-icons.net glyphs referenced by the source into a
// small generated module. Icons are CC BY 3.0 (https://game-icons.net).
//
// References recognised in src/**/*.ts(x):
//   icon: 'name'      (data definitions)
//   ic('name')        (UI helper)
//   icon="name"       (JSX prop)
//   <Icon name="name" (JSX component)
import { readFileSync, writeFileSync, readdirSync, statSync, mkdirSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const lib = JSON.parse(readFileSync(join(root, 'node_modules/@iconify-json/game-icons/icons.json'), 'utf8'));
const out = join(root, 'src/assets/icons.generated.ts');

function walk(dir, acc = []) {
  for (const f of readdirSync(dir)) {
    const p = join(dir, f);
    if (statSync(p).isDirectory()) walk(p, acc);
    else if (/\.(ts|tsx)$/.test(f) && !f.endsWith('.generated.ts')) acc.push(p);
  }
  return acc;
}

const patterns = [/icon:\s*['"]([a-z0-9-]+)['"]/g, /\bic\(\s*['"]([a-z0-9-]+)['"]\s*\)/g, /icon=['"]([a-z0-9-]+)['"]/g, /<Icon[^>]*?\bname=['"]([a-z0-9-]+)['"]/g, /icons?:\s*\[([^\]]*)\]/g];
const used = new Map();
for (const file of walk(join(root, 'src'))) {
  const src = readFileSync(file, 'utf8');
  for (const re of patterns) {
    re.lastIndex = 0;
    let m;
    while ((m = re.exec(src))) {
      const names = re.source.startsWith('icons?') ? [...m[1].matchAll(/['"]([a-z0-9-]+)['"]/g)].map((x) => x[1]) : [m[1]];
      for (const n of names) {
        if (!used.has(n)) used.set(n, `${file.replace(root + '/', '')}:${src.slice(0, m.index).split('\n').length}`);
      }
    }
  }
}

const resolve = (n) => {
  if (lib.icons[n]) return lib.icons[n].body;
  const a = lib.aliases?.[n];
  if (a && lib.icons[a.parent]) return lib.icons[a.parent].body;
  return null;
};

const missing = [];
const entries = [];
for (const [n, where] of [...used.entries()].sort()) {
  const body = resolve(n);
  if (!body) {
    missing.push(`${n}  (${where})`);
    continue;
  }
  // keep only path data so we can recolour freely
  const paths = [...body.matchAll(/d="([^"]+)"/g)].map((x) => x[1]).join(' ');
  entries.push(`  ${JSON.stringify(n)}: ${JSON.stringify(paths)},`);
}

mkdirSync(dirname(out), { recursive: true });
writeFileSync(
  out,
  `// AUTO-GENERATED by scripts/gen-icons.mjs — do not edit.\n// Icons by game-icons.net contributors, CC BY 3.0.\nexport const ICONS: Record<string, string> = {\n${entries.join('\n')}\n};\n`,
);
console.log(`icons: ${entries.length} written${missing.length ? `, ${missing.length} MISSING:` : ''}`);
if (missing.length) {
  console.log('  ' + missing.join('\n  '));
  process.exitCode = 1;
}
